"""``TensorProductGrid.is_uniform`` grades spacings relative to the axis's scale.

The test was ``ptp(spacings) < 1e-10``, absolute, so it was wrong in both directions: a grid of
spacings ``1e-13`` and ``9e-13`` read as uniform, and ``linspace`` grids of span ``1e6`` or offset
by ``1e6`` read as non-uniform. It is now ``ptp(spacings) <= 16 eps max(span, |b_0|, |b_N|)``,
twice the knot tolerance of the breakpoints read as a knot vector.

Oracle: constructed grids, uniform or not by construction; the uniform ones generated by
``linspace``, whose breakpoints carry its rounding.
"""

from __future__ import annotations

import numpy as np
import pytest

from pantr.grid import TensorProductGrid


@pytest.mark.parametrize(
    "breakpoints",
    [
        np.linspace(0.0, 1.0, 11),
        np.linspace(0.0, 1.0, 1001) * 1e6,
        np.linspace(0.0, 1.0, 11) + 1e6,
        np.linspace(-3e-12, 5e-12, 17),
        np.linspace(0.0, 1.0, 100_001),
    ],
    ids=["unit", "span-1e6", "offset-1e6", "tiny", "1e5-cells"],
)
def test_linspace_grids_are_uniform(breakpoints: np.ndarray) -> None:
    """A ``linspace`` grid is uniform at any scale and offset."""
    assert TensorProductGrid([breakpoints]).is_uniform


@pytest.mark.parametrize(
    "breakpoints",
    [np.array([0.0, 0.1, 1.0]), np.array([0.0, 0.1, 1.0]) * 1e-12],
    ids=["unit", "tiny"],
)
def test_unequal_spacings_are_not_uniform(breakpoints: np.ndarray) -> None:
    """Spacings ``0.1`` and ``0.9`` of the span are not uniform, however small the span."""
    assert not TensorProductGrid([breakpoints]).is_uniform


def test_an_axis_whose_spacings_overflow_is_not_uniform() -> None:
    """A spread of spacings (and a tolerance) beyond the double range grades nothing."""
    assert not TensorProductGrid([np.array([-1.7e308, -1.6e308, 1.7e308])]).is_uniform


@pytest.mark.parametrize(
    "breakpoints",
    [np.array([-1e308, -5e307, 0.0, 1e308]), np.array([-1.7e308, 0.0, 1e308, 1.7e308])],
    ids=["finite-spread", "wider-span"],
)
def test_an_axis_whose_tolerance_overflows_is_not_uniform(breakpoints: np.ndarray) -> None:
    """A span beyond the double range makes the tolerance infinite: it grades nothing.

    The spread of the first axis's spacings is finite (spacings ``5e307``, ``5e307`` and ``1e308``),
    so only the tolerance's own overflow decides it.
    """
    assert not TensorProductGrid([breakpoints]).is_uniform


def test_an_axis_whose_span_overflows_but_is_uniform_reads_uniform() -> None:
    """Control: the same overflowing span with equal spacings is still uniform."""
    assert TensorProductGrid([np.array([-1.7e308, 0.0, 1.7e308])]).is_uniform
