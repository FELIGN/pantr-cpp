/// Get the tolerance below which the spacings of an axis count as equal (`is_uniform`): twice the
/// knot tolerance of the breakpoints read as a knot vector, `16 eps max(span, |b_0|, |b_N|)`.
///
/// Under the knot layer's route model (`bspline::knot_merge_safety`) a breakpoint generated by an
/// ordinary route (`linspace`, a uniform or barycentric formula) is within `2 eps` times that scale
/// of its exact value, so a spacing is within `4 eps` times it plus the subtraction's own rounding,
/// and the spread of the spacings of a uniform axis within about `9 eps` times it. The factor two
/// over the knot tolerance covers that with a margin, an admitted one. The previous release's
/// absolute `1e-10` read spacings of `1e-13` and `9e-13` as uniform and `linspace` grids of span or
/// offset `1e6` as not.
///
/// Args:
///     bp (std::span<const double>): The axis's breakpoints, increasing, at least two.
///
/// Returns:
///     double: The tolerance, in the breakpoints' units.
[[nodiscard]] inline double uniform_spacing_tolerance(std::span<const double> bp) {
  return 2.0 * bspline::knot_tolerance<double>(bp);
}

/// The shared representation of a `TensorProductGrid`.
///
/// Attributes:
///     breakpoints (std::vector<std::vector<double>>): Per-axis strictly increasing breakpoints.
///     cells_per_axis (std::vector<std::int64_t>): Per-axis cell counts, `size - 1` each.
///     strides (std::vector<std::int64_t>): Per-axis C-order flat strides.
///     num_cells (std::int64_t): The product of the cell counts.
///     bounds (std::vector<double>): Row-major `(ndim, 2)` array of per-axis `[lo, hi]`.
///     is_uniform (bool): Whether every axis has constant spacing to within
///         `uniform_spacing_tolerance`.
///     bvh (pantr::detail::Lazy<BVH>): The spatial index over the cells, built on first use.
struct TensorProductGridRep {
  std::vector<std::vector<double>> breakpoints;
  std::vector<std::int64_t> cells_per_axis;
  std::vector<std::int64_t> strides;
  std::int64_t num_cells = 0;
  std::vector<double> bounds;
  bool is_uniform = true;
  pantr::detail::Lazy<BVH> bvh;
};

/// Locate one point on a tensor-product grid.
///
/// Per axis: outside `[bp_0, bp_last]` (NaN included: the comparison is negated) means outside the
/// grid; otherwise the cell index is the interval of the breakpoint vector containing the
/// coordinate, a point exactly on an interior breakpoint belonging to the lower-indexed cell and
/// a point on the outer boundary to the adjacent boundary cell. The flat id is the row-major
/// combination of the per-axis indices.
///
/// Note:
///     No validation is performed: `pt` must hold `ndim` coordinates.
///
/// Args:
///     rep (const TensorProductGridRep&): The grid.
///     pt (const double*): The point.
///
/// Returns:
///     std::int64_t: The flat cell id, or -1 for a point outside the grid or with a non-finite
///     coordinate.
[[nodiscard]] inline std::int64_t tpg_locate_core(const TensorProductGridRep& rep,
                                                  const double* pt) noexcept {
  std::int64_t cid = 0;
  for (std::size_t d = 0; d < rep.breakpoints.size(); ++d) {
    const std::vector<double>& bp = rep.breakpoints[d];
    const double x = pt[d];
    // The negated chained comparison is NaN-safe: NaN fails both bounds.
    if (!(bp.front() <= x && x <= bp.back())) {
      return -1;
    }
    // lower_bound: first index with bp[idx] >= x (numpy's searchsorted side='left'). It is at
    // most the last index since x <= bp.back(), so the cell index is at most cells - 1; it is
    // -1 only for x == bp.front(), which belongs to cell 0. The Python kernel also clamps from
    // above, which can never take effect.
    const auto idx =
        static_cast<std::int64_t>(std::lower_bound(bp.begin(), bp.end(), x) - bp.begin()) - 1;
    const std::int64_t cell_i = (std::max)(idx, std::int64_t{0});
    cid += cell_i * rep.strides[d];
  }
  return cid;
}

