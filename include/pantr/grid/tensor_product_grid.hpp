/// @file tensor_product_grid.hpp
/// @brief `TensorProductGrid`: a grid of axis-aligned boxes with one strictly increasing
/// breakpoint vector per axis.
///
/// A cell is addressed by a flat row-major (C-order) identifier; see cell_index.hpp for the
/// convention, which matches the spanwise element extraction of a B-spline space, so a grid and an
/// extraction operator built on the same space agree on cell ids.
///
/// The grid stores the per-axis breakpoints (total size `sum_k (cells_per_axis[k] + 1)`) plus a
/// handful of small metadata arrays. It never materializes per-cell bounds or connectivity; those
/// are computed on demand. The only `O(num_cells)` structure, the `BVH` behind `query_aabb`, is
/// built lazily on first query.
